<?php

namespace Symfony\Component\DependencyInjection\Loader\Configurator;

return static function (ContainerConfigurator $container) {
    $container->parameters()
        ->set('baz_class', 'BazClass')
        ->set('foo_class', \Bar\FooClass::class)
        ->set('foo', 'bar');

    $container->services()
        ->set('service_container', \Symfony\Component\DependencyInjection\ContainerInterface::class)
            ->public()
            ->synthetic()
            ->share()
        ->set('foo', \Bar\FooClass::class)
            ->public()
            ->tag('foo', ['foo' => 'foo'])
            ->tag('foo', ['bar' => 'bar', 'baz' => 'baz'])
            ->tag('foo', ['name' => 'bar', 'baz' => 'baz'])
            ->tag('nullable', ['bar' => 'bar', 'baz' => null])
            ->args([
                'foo',
                service('foo.baz'),
                ['%foo%' => 'foo is %foo%', 'foobar' => '%foo%'],
                true,
                service('service_container'),
            ])
            ->property('foo', 'bar')
            ->property('moo', service('foo.baz'))
            ->property('qux', ['%foo%' => 'foo is %foo%', 'foobar' => '%foo%'])
            ->call('setBar', [service('bar')])
            ->call('initialize', [])
            ->share()
            ->constructor('getInstance')
            ->configurator('sc_configure')
        ->set('foo.baz', '%baz_class%')
            ->public()
            ->share()
            ->constructor('getInstance')
            ->configurator(['%baz_class%', 'configureStatic1'])
        ->set('bar', \Bar\FooClass::class)
            ->public()
            ->args([
                'foo',
                service('foo.baz'),
                param('foo_bar'),
            ])
            ->share()
            ->configurator([service('foo.baz'), 'configure'])
        ->set('foo_bar', '%foo_class%')
            ->public()
            ->args([
                service('deprecated_service'),
            ])
        ->set('method_call1', \Bar\FooClass::class)
            ->public()
            ->file('%path%foo.php')
            ->call('setBar', [service('foo')])
            ->call('setBar', [service('foo2')->nullOnInvalid()])
            ->call('setBar', [service('foo3')->ignoreOnInvalid()])
            ->call('setBar', [service('foobaz')->ignoreOnInvalid()])
            ->call('setBar', [expr("service(\"foo\").foo() ~ (container.hasParameter(\"foo\") ? parameter(\"foo\") : \"default\")")])
            ->share()
        ->set('foo_with_inline', 'Foo')
            ->public()
            ->call('setBar', [service('inlined')])
            ->share()
        ->set('inlined', 'Bar')
            ->property('pub', 'pub')
            ->call('setBaz', [service('baz')])
            ->share()
        ->set('baz', 'Baz')
            ->public()
            ->call('setFoo', [service('foo_with_inline')])
            ->share()
        ->set('request', 'Request')
            ->public()
            ->synthetic()
            ->share()
        ->set('configurator_service', 'ConfClass')
            ->call('setFoo', [service('baz')])
            ->share()
        ->set('configured_service', 'stdClass')
            ->public()
            ->share()
            ->configurator([service('configurator_service'), 'configureStdClass'])
        ->set('configurator_service_simple', 'ConfClass')
            ->args([
                'bar',
            ])
            ->share()
        ->set('configured_service_simple', 'stdClass')
            ->public()
            ->share()
            ->configurator([service('configurator_service_simple'), 'configureStdClass'])
        ->set('decorated', 'stdClass')
            ->public()
            ->share()
        ->set('decorator_service', 'stdClass')
            ->public()
            ->share()
            ->decorate('decorated')
        ->set('decorator_service_with_name', 'stdClass')
            ->public()
            ->share()
            ->decorate('decorated', 'decorated.pif-pouf')
        ->set('deprecated_service', 'stdClass')
            ->public()
            ->deprecate('vendor/package', '1.1', "The \"%service_id%\" service is deprecated. You should stop using it, as it will be removed in the future.")
            ->share()
        ->set('new_factory', 'FactoryClass')
            ->property('foo', 'bar')
            ->share()
        ->set('factory_service', 'Bar')
            ->public()
            ->share()
            ->factory([service('foo.baz'), 'getInstance'])
        ->set('new_factory_service', 'FooBarBaz')
            ->public()
            ->property('foo', 'bar')
            ->share()
            ->factory([service('new_factory'), 'getInstance'])
        ->set('service_from_static_method', \Bar\FooClass::class)
            ->public()
            ->share()
            ->constructor('getInstance')
        ->set('factory_simple', 'SimpleFactoryClass')
            ->deprecate('vendor/package', '1.1', "The \"%service_id%\" service is deprecated. You should stop using it, as it will be removed in the future.")
            ->args([
                'foo',
            ])
            ->share()
        ->set('factory_service_simple', 'Bar')
            ->public()
            ->share()
            ->factory([service('factory_simple'), 'getInstance'])
        ->set('lazy_context', 'LazyContext')
            ->public()
            ->args([
                iterator(['k1' => service('foo.baz'), 'k2' => service('service_container')]),
                iterator([]),
            ])
            ->share()
        ->set('lazy_context_ignore_invalid_ref', 'LazyContext')
            ->public()
            ->args([
                iterator([service('foo.baz'), service('invalid')->ignoreOnInvalid()]),
                iterator([]),
            ])
            ->share()
        ->set('BAR', 'stdClass')
            ->public()
            ->property('bar', service('bar'))
            ->share()
        ->set('bar2', 'stdClass')
            ->public()
            ->share()
        ->set('BAR2', 'stdClass')
            ->public()
            ->share()
        ->set('tagged_iterator_foo', 'Bar')
            ->tag('foo')
            ->share()
        ->set('tagged_iterator', 'Bar')
            ->public()
            ->args([
                tagged_iterator('foo'),
            ])
            ->share()
        ->set('runtime_error', 'stdClass')
            ->public()
            ->args([
                service('errored_definition'),
            ])
            ->share()

        // Service "errored_definition" is broken.
        ->set('errored_definition', 'stdClass')
            ->share()
        ->set('preload_sidekick', 'stdClass')
            ->public()
            ->tag('container.preload', ['class' => "Some\\Sidekick1"])
            ->tag('container.preload', ['class' => "Some\\Sidekick2"])
            ->share()
        ->set('a_factory', 'Bar')
            ->share()
        ->set('a_service', 'Bar')
            ->public()
            ->share()
            ->factory([service('a_factory'), 'getBar'])
        ->set('b_service', 'Bar')
            ->public()
            ->share()
            ->factory([service('a_factory'), 'getBar'])
        ->alias('alias_for_foo', 'foo')
            ->public()
        ->alias('alias_for_alias', 'alias_for_foo')
            ->public();
};